# ========== ШАБЛОНЫ ПРОМПТОВ ==========

def build_prompt_with_memory(character: str, memory_context: str) -> str:
    """
    Собирает полный промпт с учётом характера и памяти
    """
    char_prompt = CHARS.get(character, SOUL_CHAR)
    
    if memory_context:
        return f"{LUCA_BASE}\n\n{char_prompt}\n\n{memory_context}"
    else:
        return f"{LUCA_BASE}\n\n{char_prompt}"


def build_memory_context(facts: list) -> str:
    """
    Строит контекст памяти для промпта из списка фактов
    """
    if not facts:
        return ""
    
    return f"""
ЧТО ТЫ ПОМНИШЬ О ПОЛЬЗОВАТЕЛЕ:
{chr(10).join(f"• {f}" for f in facts)}

Используй эту информацию естественно в разговоре. Не перечисляй факты списком."""
